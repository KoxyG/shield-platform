#!/usr/bin/env bash
# Regenerates src/chain/vault-bindings.ts from the ShieldVault contract's wasm.
#
# Usage: bun run bindings <path/to/shield_vault.wasm>
#   Build the wasm first, in shield-contracts: make -C contracts/shield-vault build
#   Output: target/wasm32v1-none/release/shield_vault.wasm
#
# The Stellar CLI generates bindings for @stellar/stellar-sdk v14, which used Node's
# Buffer for bytes. v17 (pinned in package.json) takes Uint8Array and needs no Buffer
# polyfill in the browser, so the output is rewritten to match. The CLI's re-exports
# of the whole SDK are dropped too; import from @stellar/stellar-sdk directly. Types
# it imports as values (ClientOptions, MethodOptions, Result) are marked `type`:
# they don't exist at runtime, so a browser bundler (Vite) fails on them.
set -euo pipefail

wasm="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"

cd "$(dirname "$0")/.."
out="src/chain/vault-bindings.ts"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# The CLI uses the folder name as an npm package name, so it must be lowercase.
stellar contract bindings typescript --wasm "$wasm" --output-dir "$tmp/shield-vault" --quiet

{
  echo "// Generated by scripts/gen-vault-bindings.sh from shield_vault.wasm. Do not edit."
  # The CLI's output doesn't meet this package's strict tsconfig (type-only imports,
  # override modifiers). Its exported types still check every call site.
  echo "// @ts-nocheck"
  perl -0pe '
    s/^import \{ Buffer \} from "buffer";\n//m;
    s/^if \(typeof window !== "undefined"\) \{.*?^\}\n//ms;
    s/^export \* (as \w+ )?from "\@stellar\/stellar-sdk[^"]*";\n//mg;
    s/\bBuffer\b/Uint8Array/g;
    s/^(\s+)(ClientOptions as ContractClientOptions|MethodOptions|Result),$/$1type $2,/mg;
  ' "$tmp/shield-vault/src/index.ts"
} > "$out"

bunx prettier --write "$out" > /dev/null
echo "Wrote $out"
